        <h3>Wrath Removal</h3>
        <p>The wrath of God that I deserve was poured out on the Song of God instead. And the righteousness of Christ is credited to me.</p>
        <p>The cup of God's wrath (Jeremiah 25:15, Isaiah 51:17, Revelation 14:10) was poured out on Jesus. In the garden of gethsemane, the night he was betrayed, Jesus prayed multiple times &quot;My Father, if it be possible, let this cup pass from me; nevertheless, not as I will but as you will&quot;.</p>
