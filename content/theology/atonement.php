        <h2>Introduction</h2>
        <p>The subject of the atonement is all about what happened on the cross. What did Jesus's death accomplish?</p>
        <p>This is a glorious subject, which we can only know in part.</p>
        <ul>
            <li>Paul prays in Ephesians for the church to <q>know the love of Christ that surpasses knowledge</q></li>
            <li>God's love is defined in terms of the atonement
                <ul>
                    <li>1 John: this is love, not that we have loved God but that he loves us and sent his Son to be the propitiation for our sins</li>
                    <li>Romans 5:8: God shows his love for us in that while we were yet sinners Christ died for us</li>
                    <li>John 3:16: God so loved the world, that he gave his only Son, that whoever believes in him should not perish by have eternal life</li>
                </ul>
            </li>
            <li>Ephesians 2 says that God saved us <strong>so that</strong> in the coming ages he might show us the immeasurable riches of his grace in kindness towards us in Christ Jesus</li>
            <li>1 Peter describes the sufferings of Christ and subsequent glories as <q>things into which angels long to look.</q></li>
        </ul>
        <p>So, what happened on the Cross? This is the love of God revealed. This is a subject we will be looking into for all eternity. This is a subject that the angels, who dwell with God, are eager to look into.</p>
        <p>There are various ways of describing what God accomplished on the Cross. Apart from this work we are in <strong>bondage</strong> to sin, <strong>separated</strong> from God, and deserving his <strong>wrath</strong>. The atonement provides the solution as <strong>redemption</strong>, <strong>reconciliation</strong>, and <strong>propitiation</strong>.</p>
        <h2>Propitiation</h2>
        <p>Jesus was a sacrifice of propitiation. This means his sacrifice removes the wrath of God from us and brings the favor of God to us. The gospel is that God is now <em>propitious</em> (favorable) towards us through the sacrifice of Jesus in the place of his people. He bore the wrath that I deserve and I am credited with his favor in God's sight.</p>
