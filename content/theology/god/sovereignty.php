            <h2>Sovereign over Sin</h2>
            <p class="summary">
                God governs human sin in a way that does not cause him to sin.
            </p>
            <p>We are getting more into the mystery of God's will. He is able to govern and ordain our sin, and yet he remains pure and sinless. There have been many attempts to explain how this can be, some of them more helpful than others, yet ultimately we must turn to God's revelation for our understanding and affirm what it affirms.</p>
            <p>Some people speak of God's <em>Decretive</em> will and God's <em>Perceptive</em> will, or His <em>Will of Decree</em> and <em>Will of Command</em>, or his <em>Sovereign Will</em> and <em>Moral Will</em>. His Decretive or Sovereign will would be what He, in his infinite wisdom, decrees to happen whether good or bad. His decrees must come to pass, but it is not as though He can be charged with wrong doing. This would include what people commonly refer to as God's Providence and all the things He Ordains to happen. His Perceptive or Moral will, on the other hand, is his revealed desire for how we are intended to act. More on this in my notes on <a href="gods-two-wills">God's two wills</a>. For the sake of this topic we will leave the explanation of God's two will aside, and focus on what scripture reveals, rather than how to make sense of potentially contradicting things.</p>
            <p>Scripture makes it plain that God is in control of the human heart (see <a href="#human-decisions">above</a>), which is also deceitful above all things and desperately sick. God gives people over to their sin, makes people wander from his ways, uses wicked nations as his rod of anger, incites Kings to disobedience, sends people through slavery, and plans the unjust death of an innocent man.</p>
